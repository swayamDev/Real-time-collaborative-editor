import type { Metadata, Viewport } from "next";
import { cookies } from "next/headers";
import { ServiceWorkerRegistration } from "@/components/service-worker";
import { BRAND, previewMetadata } from "@/lib/brand";
import { THEME_COOKIE, parseTheme } from "@/lib/preferences";
import { codeFont, documentFont, uiFont } from "./fonts";
import "./globals.css";

/**
 * Site-wide metadata. Pages set their own title ("Q3 planning notes ·
 * Brahma"); link previews stay site-wide unless a public page sets its own,
 * so a document's title never reaches a preview. The icons and the preview
 * image are generated by pnpm brand (scripts/brand.ts).
 */
export const metadata: Metadata = {
  metadataBase: new URL(process.env.BETTER_AUTH_URL ?? "http://localhost:3000"),
  title: { default: BRAND.name, template: `%s · ${BRAND.name}` },
  description: BRAND.description,
  applicationName: BRAND.name,
  icons: {
    icon: [
      { url: "/favicon.ico", sizes: "48x48" },
      { url: "/icon.svg", type: "image/svg+xml" },
    ],
    apple: [{ url: "/apple-touch-icon.png", sizes: "180x180" }],
  },
  ...previewMetadata(BRAND.name, BRAND.description),
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: BRAND.light.paper },
    { media: "(prefers-color-scheme: dark)", color: BRAND.dark.paper },
  ],
};

export default async function RootLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  const theme = parseTheme((await cookies()).get(THEME_COOKIE)?.value);
  return (
    <html
      lang="en"
      data-theme={theme}
      className={`${uiFont.variable} ${documentFont.variable} ${codeFont.variable}`}
    >
      <body>
        {children}
        <ServiceWorkerRegistration />
      </body>
    </html>
  );
}
