/**
 * Brand values used outside CSS: the web app manifest, link previews and
 * the generated icons (scripts/brand.ts). The colors mirror the design
 * tokens in src/app/globals.css; a unit test keeps them in step.
 */
export const BRAND = {
  name: "Brahma",
  shortName: "Brahma",
  /** One line, for link previews and the manifest. */
  pitch: "Real-time collaborative documents that keep working offline.",
  description:
    "A collaborative document editor with live cursors, offline editing that syncs when you reconnect, and sharing with editors and viewers.",
  light: { paper: "#f2f3f6", indigo: "#34449c", ink: "#1a1f3a", inkMuted: "#5c627a" },
  dark: { paper: "#12162b", indigo: "#9aa8f2" },
} as const;

/** The site-wide link preview image (generated by pnpm brand). */
export const PREVIEW_IMAGE = { url: "/og.png", width: 1200, height: 630, alt: `${BRAND.name}: ${BRAND.pitch}` };

/** Open Graph and Twitter metadata for a page, with the site-wide preview image. */
export function previewMetadata(title: string, description: string) {
  return {
    openGraph: { type: "website" as const, siteName: BRAND.name, title, description, images: [PREVIEW_IMAGE] },
    twitter: { card: "summary_large_image" as const, title, description, images: [PREVIEW_IMAGE.url] },
  };
}
